            <h3>The '90s and '00s: Expansion</h3>
            <div>
                <p>By the 1990s the need for data infrastructure had expanded to businesses of all sizes. While initially effective, on premises data storage made scaling difficult, as organisations required large capital investments to expand their data infrastructure. This along with a surge in demand due to the ".com" (Silicon Angle, 2014) boom paved the way for the next evolution: purpose built data centres.</p>
                <p>The 2000s saw the construction of purpose built data centres, these facilities were created to provide reliable and easily accessible storage of massive amounts of data, featuring extensive redundancy systems for power, cooling, and fire supression (TRG Datacenteres, n.d.). These centres made it possible for cloud computing giants like Amazon Web Services and Microsoft Azure to emerge, providing computing solutions to companies that would otherwise require their own infrastructure
