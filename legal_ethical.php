                <h4>Deontology</h4>
                <p>The "green light" utilitarianism offers to data centre expansion starts to unravel under a deontological lens. When we see examples of residents having access to water threatened by developments, it is hard for me to argue that companies are acting within the "necessity to act out of reverence for the moral law" as deemed necessary by Kantian ethics (Kant, n.d.)</p>
                <p>This lack of concern with "absolute duty" is further seen with the environmental impacts of data centre developments are considered. Previous pages discuss how water and electricity resources are being strained, with some politicians going so far as to conclude that data centres are "cannabilising our renewables" (Lynn Boylan, 2026).</p>
