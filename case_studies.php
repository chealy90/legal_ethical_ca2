            <p>
                Kildare residents took part in Ireland's first national protest against data centres in Dublin in November 2026. Marchers were demonstrating against the development of multiple approved sites across Kildare, including a €3 billion complex for Herbata Ltd in Naas, as well as a 54.55 hectare site for Microsoft. In addition to this, there are further plans for another centre in Leixlip (Kildare Nationalist, 2026).
